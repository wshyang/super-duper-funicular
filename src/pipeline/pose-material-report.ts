import fs from 'node:fs';
import path from 'node:path';
import type { PoseMaterialAuditReport, SourceEvidence } from './pose-material-types.js';
import type { PoseMaterialAuditResult } from './pose-material-audit.js';

export interface ReportWriteOptions {
  readonly outDir: string;
  readonly jsonPath: string;
}

function percent(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

function statusBadge(source: SourceEvidence): string {
  const map: Record<string, string> = {
    accepted: 'ACCEPTED',
    conditional: 'conditional',
    rejected: 'rejected',
    'material-gap': 'material-gap',
  };
  return map[source.status] ?? source.status;
}

function sourceRow(source: SourceEvidence): string {
  const eligible = source.parts.filter((part) => part.eligible).length;
  const registration = source.registration;
  const scale = `${(source.faceScaleRatio * 100).toFixed(1)}%`;
  const match = `${(source.poseMatchRatio * 100).toFixed(0)}%`;
  const best = source.reasonCodes.includes('declared-phase-mismatch') ? 'mismatch' : 'ok';
  return [
    `| \`${source.sourceId}\` | ${statusBadge(source)} | ${source.figureHeightPx} | ${scale} |`,
    `${percent(source.interiorLeakRatio ?? 0)} | ${percent(source.shadowFraction)} |`,
    `${registration ? registration.poseF1.toFixed(3) : 'n/a'} | ${match} | ${eligible}/16 | ${best} |`,
    `${source.reasonCodes.join(', ') || '—'} |`,
  ].join(' ');
}

function renderSourceTable(sources: readonly SourceEvidence[]): string {
  const header = [
    '| Source | Status | Height px | Face scale | Spill | Shadow | poseF1 | Match | Eligible parts | Phase | Reasons |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
  ];
  return [...header, ...sources.map(sourceRow)].join('\n');
}

function renderBucketTable(report: PoseMaterialAuditReport): string {
  const lines = [
    '| Part | Buckets (measured angle → sources) |',
    '|---|---|',
  ];
  const byPart = new Map<string, string[]>();
  for (const entry of report.buckets) {
    const list = byPart.get(entry.partId) ?? [];
    list.push(`${entry.bucketDeg}°×${entry.sources.length}`);
    byPart.set(entry.partId, list);
  }
  for (const [partId, buckets] of [...byPart.entries()].sort()) {
    lines.push(`| \`${partId}\` | ${buckets.join(' · ')} |`);
  }
  return lines.join('\n');
}

function renderGapTable(report: PoseMaterialAuditReport): string {
  if (report.gaps.length === 0) return '_No material gaps: every audited part/phase pair has eligible material._';
  const lines = [
    '| Part | Phase index | Target angle | Target bucket | Why |',
    '|---|---|---|---|---|',
  ];
  for (const gap of report.gaps.slice(0, 80)) {
    lines.push(`| \`${gap.partId}\` | ${gap.phaseIndex} | ${gap.targetAngleDeg}° | ${gap.targetBucketDeg}° | ${gap.reason} |`);
  }
  return lines.join('\n');
}

function renderDiversity(result: PoseMaterialAuditResult): string {
  const diversity = result.diversity;
  const duplicates = diversity.duplicatePairs;
  const lines = [
    `- Sources compared: **${diversity.labels.length}**`,
    `- Mean pairwise silhouette IoU: **${diversity.meanPairIou.toFixed(3)}**`,
    `- Worst pair: **${diversity.maxPairIou.toFixed(3)}**${diversity.worstPair ? ` (\`${diversity.worstPair[0]}\` vs \`${diversity.worstPair[1]}\`)` : ''}`,
    `- Duplicate pairs at IoU ≥ 0.95: **${duplicates.length}**`,
    `- Distinct pose clusters: **${diversity.clusters}** of ${diversity.labels.length}`,
  ];
  if (duplicates.length > 0) {
    lines.push('');
    lines.push('Duplicate pairs:');
    for (const [a, b, iou] of duplicates) lines.push(`- \`${a}\` ≈ \`${b}\` (${iou.toFixed(3)})`);
  }
  return lines.join('\n');
}

function renderPartDetail(source: SourceEvidence): string {
  const eligible = source.parts.filter((part) => part.eligible);
  if (eligible.length === 0) return `- \`${source.sourceId}\`: no eligible parts (${source.reasonCodes.join(', ')})`;
  const details = eligible
    .map((part) => `${part.partId}@${part.bucketDeg}° v${part.fit.visibility}`)
    .join(', ');
  return `- \`${source.sourceId}\`: ${details}`;
}

export function renderPoseMaterialMarkdown(result: PoseMaterialAuditResult): string {
  const report = result.report;
  const counts = report.eligibilityCounts;
  const lines = [
    '# Pose-Material Audit (PMAC)',
    '',
    'Generated by `npm run pose-material:audit`. Acceptance criteria:',
    '[`docs/POSE_MATERIAL_ACCEPTANCE.md`](./POSE_MATERIAL_ACCEPTANCE.md).',
    '',
    '## Summary',
    '',
    `- Sources audited: **${report.sources.length}**`,
    `- Accepted: **${counts.accepted ?? 0}** · Conditional: **${counts.conditional ?? 0}** · Rejected: **${counts.rejected ?? 0}**`,
    `- Material buckets discovered: **${report.buckets.length}**`,
    `- Material gaps (part × phase): **${report.gaps.length}**`,
    '',
    '## Per-source measurements',
    '',
    renderSourceTable(report.sources),
    '',
    '`poseF1` is the silhouette agreement between the source and the pose the generator was told to',
    'produce; it is computed from pixels after a head-anchored similarity registration, not from the',
    'prompt. `Face scale` is the measured face-profile width relative to the accepted master: it is',
    'pose-invariant (a crouched flight frame has a shorter silhouette but the same face width), so it',
    'separates scale/identity drift from pose change. Values outside 90–110 % are `identity-drift`.',
    '',
    '## Pose diversity of the source pool',
    '',
    renderDiversity(result),
    '',
    '## Measured angle buckets',
    '',
    renderBucketTable(report),
    '',
    '## Material gaps (AC-8)',
    '',
    renderGapTable(report),
    '',
    '## Eligible parts per source',
    '',
    ...report.sources.map(renderPartDetail),
    '',
  ];
  return lines.join('\n');
}

export function writePoseMaterialReport(
  result: PoseMaterialAuditResult,
  options: ReportWriteOptions,
): void {
  fs.mkdirSync(options.outDir, { recursive: true });
  fs.mkdirSync(path.dirname(options.jsonPath), { recursive: true });
  fs.writeFileSync(path.join(options.outDir, 'POSE_MATERIAL_AUDIT.md'), `${renderPoseMaterialMarkdown(result)}\n`);
  fs.writeFileSync(options.jsonPath, `${JSON.stringify({
    report: result.report,
    diversity: result.diversity,
  }, null, 2)}\n`);
}
