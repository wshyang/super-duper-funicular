export function selectPhaseVariantBankForPose(
  pose: ArticulatedPose,
  canonicalBank: PhotorealPartBank,
  variantBank: PhotorealPhaseVariantBank,
): PhotorealPartBank {
  const out: Partial<Record<BodyPartId, RasterImage>> = { ...canonicalBank };
  const pick = (partId: BodyPartId, variantId: Exclude<PhaseJigVariantId, 'canonical'>): void => {
    const found = variantBank[partId]?.[variantId]?.image;
    if (found) out[partId] = found;
  };
  if (pose.nearArm.endEffector.x > pose.collar.x + 2) {
    pick('nearUpperArm', 'forward-drive');
    pick('nearForearm', 'forward-drive');
    pick('nearHand', 'forward-drive');
  }
  if (pose.farArm.endEffector.x < pose.collar.x - 2) {
    pick('farUpperArm', 'rear-extension');
    pick('farForearm', 'rear-extension');
  }
  if (pose.nearLeg.midJoint.y < pose.pelvis.y + 18 && pose.nearLeg.midJoint.x > pose.pelvis.x + 8) {
    pick('nearThigh', 'high-knee-flexed');
    pick('nearShin', 'high-knee-flexed');
  }
  if (pose.farLeg.midJoint.x < pose.pelvis.x - 10) {
    pick('farThigh', 'split-extension');
  }
  if (pose.nearLeg.heelPoint.y < pose.nearLeg.ballPoint.y - 3) {
    pick('nearFoot', 'plantar-toe-off');
  } else if (pose.nearLeg.tipPoint.y < pose.nearLeg.heelPoint.y - 1) {
    pick('nearFoot', 'dorsiflexed-strike');
  }
  if (pose.farLeg.heelPoint.y < pose.farLeg.ballPoint.y - 3) {
    pick('farFoot', 'plantar-toe-off');
  }
  if (pose.isFlightPhase) {
    pick('hairAccessory', 'horizontal-whip');
  }
  return out;
}
