export type VisibilityScore = 0 | 1 | 2 | 3;

export type PhaseJigVariantId =
  | 'canonical'
  | 'forward-drive'
  | 'rear-extension'
  | 'high-knee-flexed'
  | 'split-extension'
  | 'dorsiflexed-strike'
  | 'plantar-toe-off'
  | 'horizontal-whip'
  | 'bare-horizontal-reach'
  | 'bare-vertical-stance'
  | 'bare-hamstring-curl'
  | 'bare-vertical-up'
  | 'bare-front-kick';

export interface PhaseFrameComplianceEntry {
  readonly frameId: PhaseFrameId;
  readonly callId: string;
  readonly poseCode: string;
  readonly complianceStatus: 'accepted' | 'rejected-for-primary-target-retained-for-secondary';
  readonly rejectionDefectCode?: 'IMG-ERR-17' | 'IMG-ERR-18' | 'IMG-ERR-19' | 'IMG-ERR-20';
  readonly promptRefinementSummary: string;
  readonly partVisibilityScores: Readonly<Record<BodyPartId, VisibilityScore>>;
}

export interface PhaseVariantJigSpec extends PhaseJigSegmentSpec {
  readonly variantId: Exclude<PhaseJigVariantId, 'canonical'>;
  readonly variantKey: `${BodyPartId}--${Exclude<PhaseJigVariantId, 'canonical'>}`;
  readonly phaseTriggerDescription: string;
}

export interface HarvestedJigVariant {
  readonly partId: BodyPartId;
  readonly variantId: Exclude<PhaseJigVariantId, 'canonical'>;
  readonly variantKey: string;
  readonly sourceFrameId: PhaseFrameId;
  readonly phaseTriggerDescription: string;
  readonly image: RasterImage;
  readonly metrics: PhaseLimbClearanceMetrics;
}

export type PhotorealPhaseVariantBank = Readonly<
  Partial<Record<BodyPartId, Readonly<Partial<Record<Exclude<PhaseJigVariantId, 'canonical'>, HarvestedJigVariant>>>>>
>;

